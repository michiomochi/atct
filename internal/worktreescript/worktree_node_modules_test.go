func TestDetachSeversSymlinkBeforeInstalling(t *testing.T) {
	r := newTestRepo(t)
	primaryEntries := directoryEntries(t, r.primary)
	primaryInfo := fileInfo(t, r.primary)

	output, err := r.run(r.worktree, "status")
	if err != nil {
		t.Fatalf("status before detach: %v\n%s", err, output)
	}
	if !strings.Contains(output, "attached") {
		t.Fatalf("status before detach = %q, want attached", output)
	}

	output, err = r.run(r.worktree, "detach")
	if err != nil {
		t.Fatalf("detach: %v\n%s", err, output)
	}

	worktreeNodeModules := filepath.Join(r.worktree, "web", "node_modules")
	info := lstat(t, worktreeNodeModules)
	if info.Mode()&os.ModeSymlink != 0 {
		t.Fatalf("worktree node_modules is still a symlink: %s", worktreeNodeModules)
	}
	if !info.IsDir() {
		t.Fatalf("worktree node_modules is not a directory: %s", worktreeNodeModules)
	}

	fakeInstall := filepath.Join(worktreeNodeModules, "FAKE-INSTALL")
	contents := string(fileContents(t, fakeInstall))
	lines := strings.Split(strings.TrimSuffix(contents, "\n"), "\n")
	if len(lines) < 2 {
		t.Fatalf("FAKE-INSTALL = %q, want cwd and args lines", contents)
	}
	worktreeWeb, err := filepath.EvalSymlinks(filepath.Join(r.worktree, "web"))
	if err != nil {
		t.Fatal(err)
	}
	if lines[0] != worktreeWeb {
		t.Fatalf("FAKE-INSTALL cwd = %q, want %q", lines[0], worktreeWeb)
	}
	if !strings.Contains(lines[1], "args: install") || !strings.Contains(lines[1], "--frozen-lockfile") {
		t.Fatalf("FAKE-INSTALL args = %q, want install and --frozen-lockfile", lines[1])
	}

	if _, err := os.Stat(filepath.Join(r.primary, "FAKE-INSTALL")); !os.IsNotExist(err) {
		t.Fatalf("primary node_modules was modified: FAKE-INSTALL stat error = %v", err)
	}
	if got := directoryEntries(t, r.primary); !reflect.DeepEqual(got, primaryEntries) {
		t.Fatalf("primary node_modules entries = %v, want %v", got, primaryEntries)
	}
	if !os.SameFile(primaryInfo, fileInfo(t, r.primary)) {
		t.Fatalf("primary node_modules inode changed")
	}

	output, err = r.run(r.worktree, "status")
	if err != nil {
		t.Fatalf("status after detach: %v\n%s", err, output)
	}
	if !strings.Contains(output, "detached") {
		t.Fatalf("status after detach = %q, want detached", output)
	}
}

func TestDetachIsIdempotent(t *testing.T) {
	r := newTestRepo(t)
	if output, err := r.run(r.worktree, "detach"); err != nil {
		t.Fatalf("first detach: %v\n%s", err, output)
	}

	fakeInstall := filepath.Join(r.worktree, "web", "node_modules", "FAKE-INSTALL")
	beforeContents := fileContents(t, fakeInstall)
	beforeInfo := fileInfo(t, fakeInstall)
	if output, err := r.run(r.worktree, "detach"); err != nil {
		t.Fatalf("second detach: %v\n%s", err, output)
	}
	afterContents := fileContents(t, fakeInstall)
	afterInfo := fileInfo(t, fakeInstall)
	if !reflect.DeepEqual(afterContents, beforeContents) {
		t.Fatalf("FAKE-INSTALL changed on second detach: before %q, after %q", beforeContents, afterContents)
	}
	if !afterInfo.ModTime().Equal(beforeInfo.ModTime()) {
		t.Fatalf("FAKE-INSTALL mtime changed on second detach: before %v, after %v", beforeInfo.ModTime(), afterInfo.ModTime())
	}
}

func TestAttachRestoresSymlink(t *testing.T) {
	r := newTestRepo(t)
	if output, err := r.run(r.worktree, "detach"); err != nil {
		t.Fatalf("detach: %v\n%s", err, output)
	}
	output, err := r.run(r.repo, "attach", "1", "--yes")
	if err != nil {
		t.Fatalf("attach: %v\n%s", err, output)
	}

	worktreeNodeModules := filepath.Join(r.worktree, "web", "node_modules")
	info := lstat(t, worktreeNodeModules)
	if info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("worktree node_modules is not a symlink")
	}
	target, err := os.Readlink(worktreeNodeModules)
	if err != nil {
		t.Fatalf("Readlink: %v", err)
	}
	primaryTarget, err := filepath.EvalSymlinks(r.primary)
	if err != nil {
		t.Fatalf("EvalSymlinks primary node_modules: %v", err)
	}
	if target != primaryTarget {
		t.Fatalf("node_modules symlink target = %q, want %q", target, primaryTarget)
	}
	if !os.SameFile(fileInfo(t, r.primary), fileInfo(t, worktreeNodeModules)) {
		t.Fatalf("attached node_modules does not resolve to primary node_modules")
	}

	output, err = r.run(r.repo, "status", "1")
	if err != nil {
		t.Fatalf("status after attach: %v\n%s", err, output)
	}
	if !strings.Contains(output, "attached") {
		t.Fatalf("status after attach = %q, want attached", output)
	}
}

func TestAttachWithoutYesRefuses(t *testing.T) {
	r := newTestRepo(t)
	if output, err := r.run(r.worktree, "detach"); err != nil {
		t.Fatalf("detach: %v\n%s", err, output)
	}

	output, err := r.run(r.repo, "attach", "1")
	if err == nil {
		t.Fatalf("attach without --yes succeeded, output %q", output)
	}
	info := lstat(t, filepath.Join(r.worktree, "web", "node_modules"))
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		t.Fatalf("node_modules changed after attach without --yes: mode %s", info.Mode())
	}
}

func TestAttachRefusesOutsideWorktrees(t *testing.T) {
	r := newTestRepo(t)
	if output, err := r.run(r.worktree, "detach"); err != nil {
		t.Fatalf("detach: %v\n%s", err, output)
	}

	outside := filepath.Join(filepath.Dir(r.repo), "outside-worktree")
	if err := os.Rename(r.worktree, outside); err != nil {
		t.Fatalf("move worktree outside .worktrees: %v", err)
	}
	if err := os.Symlink(outside, r.worktree); err != nil {
		t.Fatalf("replace worktree with symlink: %v", err)
	}

	output, err := r.run(r.repo, "attach", "1", "--yes")
	if err == nil {
		t.Fatalf("attach outside .worktrees succeeded, output %q", output)
	}
	nodeModules := filepath.Join(outside, "web", "node_modules")
	info := lstat(t, nodeModules)
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		t.Fatalf("outside node_modules was removed or replaced: mode %s", info.Mode())
	}
	if _, err := os.Stat(filepath.Join(nodeModules, "FAKE-INSTALL")); err != nil {
		t.Fatalf("outside node_modules marker missing: %v", err)
	}
}

func TestSetupLeavesSymlink(t *testing.T) {
	r := newTestRepo(t)
	output, err := r.run(r.repo, "setup", "2")
	if err != nil {
		t.Fatalf("worktree-setup.sh 2: %v\n%s", err, output)
	}

	worktreeNodeModules := filepath.Join(r.repo, ".worktrees", "2", "web", "node_modules")
	info := lstat(t, worktreeNodeModules)
	if info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("setup detached node_modules instead of leaving symlink")
	}
	target, err := os.Readlink(worktreeNodeModules)
	if err != nil {
		t.Fatalf("Readlink: %v", err)
	}
	if target != r.primary {
		t.Fatalf("setup symlink target = %q, want %q", target, r.primary)
	}
}

func newTestRepo(t *testing.T) *testRepo {
	t.Helper()
	_, testFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	sourceRoot, err := filepath.Abs(filepath.Join(filepath.Dir(testFile), "..", ".."))
	if err != nil {
		t.Fatalf("source root: %v", err)
	}

	repo := filepath.Join(t.TempDir(), "repo")
	if err := os.MkdirAll(filepath.Join(repo, "script"), 0o755); err != nil {
		t.Fatalf("mkdir repo: %v", err)
	}
	runGit(t, "", "init", "-b", "main", repo)

	writeFile(t, filepath.Join(repo, ".gitignore"), "web/node_modules/\n", 0o644)
	copyFile(t, filepath.Join(sourceRoot, "script", "worktree-node-modules.sh"), filepath.Join(repo, "script", "worktree-node-modules.sh"), 0o755)
	copyFile(t, filepath.Join(sourceRoot, "script", "worktree-setup.sh"), filepath.Join(repo, "script", "worktree-setup.sh"), 0o755)
	writeFile(t, filepath.Join(repo, "web", "package.json"), "{}\n", 0o644)
	writeFile(t, filepath.Join(repo, "web", "pnpm-lock.yaml"), "", 0o644)
	writeFile(t, filepath.Join(repo, "web", "dist", "index.html"), "<!doctype html>\n", 0o644)
	primary := filepath.Join(repo, "web", "node_modules")
	if err := os.MkdirAll(primary, 0o755); err != nil {
		t.Fatalf("mkdir primary node_modules: %v", err)
	}
	writeFile(t, filepath.Join(primary, "PRIMARY-MARKER"), "primary\n", 0o644)

	runGit(t, repo, "-c", "user.name=Test User", "-c", "user.email=test@example.com", "add", "-A")
	runGit(t, repo, "-c", "user.name=Test User", "-c", "user.email=test@example.com", "commit", "-m", "initial")
	worktree := filepath.Join(repo, ".worktrees", "1")
	if err := os.MkdirAll(filepath.Dir(worktree), 0o755); err != nil {
		t.Fatalf("mkdir worktrees: %v", err)
	}
	runGit(t, repo, "worktree", "add", worktree, "-b", "wt/goal-1")
	if err := os.Symlink(primary, filepath.Join(worktree, "web", "node_modules")); err != nil {
		t.Fatalf("create worktree node_modules symlink: %v", err)
	}

	fakePNPM := filepath.Join(filepath.Dir(repo), "bin", "fake-pnpm")
	writeFile(t, fakePNPM, "#!/bin/sh\nmkdir -p node_modules/.pnpm\nprintf '%s\\n' \"$PWD\" > node_modules/FAKE-INSTALL\nprintf 'args: %s\\n' \"$*\" >> node_modules/FAKE-INSTALL\n", 0o755)

	return &testRepo{
		repo:     repo,
		worktree: worktree,
		primary:  primary,
		script:   filepath.Join(repo, "script", "worktree-node-modules.sh"),
		fakePNPM: fakePNPM,
	}
}

func (r *testRepo) run(dir string, args ...string) (string, error) {
	if args[0] == "setup" {
		args[0] = filepath.Join(r.repo, "script", "worktree-setup.sh")
	} else {
		args = append([]string{r.script}, args...)
	}
	cmd := exec.Command(args[0], args[1:]...)
	cmd.Dir = dir
	cmd.Env = testEnv(map[string]string{"PNPM": r.fakePNPM})
	output, err := cmd.CombinedOutput()
	return string(output), err
}

func runGit(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = testEnv(nil)
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, output)
	}
	return string(output)
}

func testEnv(overrides map[string]string) []string {
	env := make([]string, 0, len(os.Environ())+len(overrides)+2)
	for _, entry := range os.Environ() {
		if strings.HasPrefix(entry, "GIT_CONFIG_GLOBAL=") || strings.HasPrefix(entry, "GIT_CONFIG_SYSTEM=") || strings.HasPrefix(entry, "PNPM=") {
			continue
		}
		env = append(env, entry)
	}
	env = append(env, "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_SYSTEM=/dev/null")
	for key, value := range overrides {
		env = append(env, fmt.Sprintf("%s=%s", key, value))
	}
	return env
}

func copyFile(t *testing.T, source, destination string, mode os.FileMode) {
	t.Helper()
	contents, err := os.ReadFile(source)
	if err != nil {
		t.Fatalf("read %s: %v", source, err)
	}
	writeFile(t, destination, string(contents), mode)
}

func writeFile(t *testing.T, path, contents string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(contents), mode); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatalf("chmod %s: %v", path, err)
	}
}

func directoryEntries(t *testing.T, path string) []string {
	t.Helper()
	entries, err := os.ReadDir(path)
	if err != nil {
		t.Fatalf("ReadDir %s: %v", path, err)
	}
	names := make([]string, 0, len(entries))
	for _, entry := range entries {
		names = append(names, entry.Name())
	}
	sort.Strings(names)
	return names
}

func fileContents(t *testing.T, path string) []byte {
	t.Helper()
	contents, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return contents
}

func fileInfo(t *testing.T, path string) os.FileInfo {
	t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat %s: %v", path, err)
	}
	return info
}

func lstat(t *testing.T, path string) os.FileInfo {
	t.Helper()
	info, err := os.Lstat(path)
	if err != nil {
		t.Fatalf("lstat %s: %v", path, err)
	}
	return info
}
